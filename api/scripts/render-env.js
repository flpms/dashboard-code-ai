#!/usr/bin/env node
'use strict';

/**
 * Writes the `.env` a deploy ships, from the environment CI already has.
 *
 * Replaces the hand-written `echo NAME=$NAME >> .env` ladder that every
 * release workflow grows. That ladder drifts: someone adds a variable to the
 * code and forgets the echo, and the service boots with `undefined` — failing
 * later, inside a use case, far from the cause. Here the manifest is the list,
 * so the file cannot be missing a name the code reads.
 *
 * Usage: node scripts/render-env.js [outputPath]     (default: ./.env)
 */

import { writeFileSync } from 'node:fs';

import { ENV_MANIFEST, missingEnvVariables } from '../app/config/env.manifest.js';

const output = process.argv[2] || '.env';

const missing = missingEnvVariables(process.env);

if (missing.length) {
  console.error('Cannot render .env — these required variables are not set:');
  missing.forEach(name => console.error(`  - ${name}: ${ENV_MANIFEST[name].doc}`));
  process.exit(1);
}

// Values are single-quoted and inner quotes escaped, so a secret containing a
// space, a `#`, or a `$` survives the round trip through dotenv intact.
const quote = value => `'${String(value).replace(/'/g, "'\\''")}'`;

const lines = Object.entries(ENV_MANIFEST)
  .filter(([name]) => process.env[name] !== undefined && process.env[name] !== '')
  .map(([name]) => `${name}=${quote(process.env[name])}`);

const header = [
  '# Generated by scripts/render-env.js — do not edit by hand.',
  `# Source of truth: app/config/env.manifest.js`,
  `# Rendered at ${new Date().toISOString()}`,
  process.env.COMMIT_SHA ? `COMMIT_SHA=${quote(process.env.COMMIT_SHA)}` : null,
].filter(Boolean);

writeFileSync(output, [...header, ...lines, ''].join('\n'), { mode: 0o600 });

const secrets = Object.entries(ENV_MANIFEST).filter(([, entry]) => entry.secret).length;

console.log(
  `Wrote ${lines.length} variables to ${output} (${secrets} marked secret, values not logged).`
);
