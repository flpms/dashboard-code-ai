#!/usr/bin/env node

/**
 * Turns the template into your project.
 *
 * Renames the packages and deploy targets, generates real secrets, and writes
 * both `.env` files. Idempotent: running it twice with the same name changes
 * nothing the second time (secrets are only generated when a `.env` is absent).
 *
 *   node scripts/bootstrap.mjs --name="Order Book" [--slug=order-book] [--force-env]
 *
 * No dependencies — it runs before any `npm install`.
 */

import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const parseArgs = argv =>
  argv.reduce(
    (args, arg) => {
      if (arg === '--force-env') return { ...args, forceEnv: true };
      const match = arg.match(/^--([^=]+)=(.*)$/);
      return match ? { ...args, [match[1]]: match[2] } : args;
    },
    { forceEnv: false }
  );

const slugify = value =>
  value
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const args = parseArgs(process.argv.slice(2));

if (!args.name) {
  console.error('Usage: node scripts/bootstrap.mjs --name="My Project" [--slug=my-project]');
  process.exit(1);
}

const name = args.name;
const slug = args.slug ? slugify(args.slug) : slugify(name);

if (!slug) {
  console.error(`Could not derive a slug from "${name}". Pass --slug explicitly.`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// 1. Rename

// Every literal the template uses to name itself, and what it becomes. A table
// rather than a chain of sed calls: adding a rename is a row.
const REPLACEMENTS = [
  { from: /@template\/api/g, to: `@${slug}/api` },
  { from: /@template\/web/g, to: `@${slug}/web` },
  { from: /^name: template$/m, to: `name: ${slug}` },
  { from: /template-db/g, to: `${slug}-db` },
  { from: /template-api/g, to: `${slug}-api` },
  { from: /PUBLIC_APP_NAME=Template/g, to: `PUBLIC_APP_NAME=${name}` },
];

const TARGETS = [
  'api/package.json',
  'api/docker-compose.yml',
  'api/.env.example',
  'web/package.json',
  'web/.env.example',
  'README.md',
];

const rewritten = TARGETS.filter(relative => {
  const path = join(root, relative);
  if (!existsSync(path)) return false;

  const before = readFileSync(path, 'utf8');
  const after = REPLACEMENTS.reduce((text, { from, to }) => text.replace(from, to), before);

  if (before === after) return false;

  writeFileSync(path, after);
  return true;
});

// ---------------------------------------------------------------------------
// 2. Secrets and .env files

const secret = bytes => randomBytes(bytes).toString('base64url');

const writeEnv = (relative, contents) => {
  const path = join(root, relative);

  if (existsSync(path) && !args.forceEnv) return { relative, written: false };

  writeFileSync(path, contents, { mode: 0o600 });
  return { relative, written: true };
};

const mongoPassword = secret(18);

const apiEnv = `# Generated by scripts/bootstrap.mjs for "${name}".
# Every name here is declared in api/app/config/env.manifest.js.

NODE_ENV=development
PORT=3001
LOG_LEVEL=verbose
LOG_PATH=

APP_URL=http://localhost:5173
CORS_ALLOWED_ORIGINS=http://localhost:5173

JWT_SECRET=${secret(48)}
JWT_EXPIRES_IN=2h

MONGO_CONNECTION=mongodb://root:${mongoPassword}@localhost:27017/${slug}?authSource=admin
MONGO_INITDB_ROOT_USERNAME=root
MONGO_INITDB_ROOT_PASSWORD=${mongoPassword}
MONGO_INITDB_DATABASE=${slug}

USERS_COLLECTION=users
ITEMS_COLLECTION=items
HISTORY_COLLECTION=history

STORAGE_ENDPOINT=
STORAGE_REGION=auto
STORAGE_ACCESS_KEY_ID=
STORAGE_SECRET_ACCESS_KEY=
STORAGE_FILES_BUCKET=
STORAGE_SIGNED_URL_TTL=900
`;

const webEnv = `# Generated by scripts/bootstrap.mjs for "${name}".
# Everything the browser receives must be PUBLIC_* — and is therefore not secret.

PUBLIC_API_URL=http://localhost:3001
PUBLIC_APP_NAME=${name}
`;

const envResults = [writeEnv('api/.env', apiEnv), writeEnv('web/.env', webEnv)];

// ---------------------------------------------------------------------------
// 3. Report

const skipped = envResults.filter(result => !result.written).map(result => result.relative);

console.log(`\n  ${name}  (${slug})\n`);
console.log(`  Renamed        ${rewritten.length} file(s)`);
console.log(`  Wrote          ${envResults.filter(r => r.written).map(r => r.relative).join(', ') || 'nothing'}`);

if (skipped.length) {
  console.log(`  Left untouched ${skipped.join(', ')} (already existed — pass --force-env to overwrite)`);
}

console.log(`
  Next:

    docker compose -f api/docker-compose.yml up -d mongodb
    cd api && npm ci && npm run seed:admin --  --email=you@example.com --name="You" --tenantId=$(node -e "console.log(require('crypto').randomBytes(12).toString('hex'))")
    npm run dev

    cd ../web && npm ci && npm run dev

  Then read docs/ARCHITECTURE.md and .claude/skills/code-style/SKILL.md.
`);
